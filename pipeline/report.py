"""Turn results/*.json into a markdown table and a plot. Only numbers present in the JSON are shown."""

import json
import os
from typing import List, Optional


def _fmt(x, nd=2):
    if x is None:
        return "-"
    if isinstance(x, float) and x != x:  # NaN
        return "-"
    return f"{x:.{nd}f}"


def _sci(x):
    return "-" if x is None else f"{x:.3e}"


def load_results(paths: List[str]) -> List[dict]:
    out = []
    for p in paths:
        with open(p) as f:
            r = json.load(f)
        r["_path"] = p
        out.append(r)
    return out


def markdown_for(result: dict) -> str:
    env, model, data, proto = result["environment"], result["model"], result["dataset"], result["protocol"]
    hw = env.get("gpu") or env.get("cpu")
    lines = [
        f"### {model['model_key']} on {env['device']} ({hw})",
        "",
        f"- Checkpoint: `{model['repo_id']}`" + (f" @ `{model['revision'][:10]}`" if model.get("revision") else ""),
        f"- Software: torch {env['torch']}, lerobot {env.get('lerobot')}, transformers {env.get('transformers')}, "
        f"CUDA {env.get('cuda_runtime')}, {env['torch_num_threads']} CPU threads",
        f"- Eval data: {data.get('num_frames')} frames from `{data.get('dataset')}` "
        f"({data.get('num_tasks', '?')} tasks, seed {data.get('seed')}), action horizon {data.get('horizon', '-')}",
        f"- Latency: batch {proto['latency_batch_size']}, {proto['warmup_runs']} warmup + {proto['timed_runs']} timed runs, "
        f"same device for every row; 95% CIs are bootstrap (p50) / normal (mean)",
        "",
    ]
    gt = proto.get("ground_truth_metrics")
    head = ["Variant", "Precision", "Size (MB)", "Params (M)", "p50 ms [95% CI]", "p95 ms", "Samples/s",
            "Rel. L2 vs FP32"]
    if gt:
        head += ["Next-action MSE vs GT", "Chunk MSE vs GT", "Chunk MSE change vs FP32"]
    lines.append("| " + " | ".join(head) + " |")
    lines.append("|" + "---|" * len(head))
    floor = None
    for v in result["variants"]:
        if "skipped" in v:
            lines.append(f"| {v['variant']} | skipped: {v['skipped']} |" + " |" * (len(head) - 2))
            continue
        inf = v["latency"]["inference"]
        ci = inf["p50_ci95_ms"]
        row = [v["variant"], v["precision"], _fmt(v["size_mb"], 1), _fmt(v["num_parameters"] / 1e6, 1),
               f"{_fmt(inf['p50_ms'])} [{_fmt(ci[0])}, {_fmt(ci[1])}]", _fmt(inf["p95_ms"]),
               _fmt(inf["throughput_samples_per_s"]), _fmt(v["agreement_with_fp32"]["rel_l2_mean"], 4)]
        if gt:
            g = v.get("vs_ground_truth", {})
            d = v.get("degradation_vs_fp32", {})
            row += [_sci(g.get("next_action", {}).get("mse")), _sci(g.get("chunk", {}).get("mse")),
                    "baseline" if v["variant"] == "fp32" else (_fmt(d.get("chunk_mse_delta_pct"), 1) + "%")]
        lines.append("| " + " | ".join(row) + " |")
        if "noise_floor" in v:
            floor = v["noise_floor"]
    lines.append("")
    if floor:
        lines.append(f"Noise floor: FP32 run with a different flow-matching noise seed differs from FP32 by "
                     f"rel. L2 {floor['rel_l2_mean']:.4f} (mean over frames). Variants below this change the "
                     f"output less than resampling the noise does.")
        lines.append("")
    if not gt:
        lines.append("Ground-truth columns omitted: " + (model.get("notes") or "no ground truth for this model/data."))
        lines.append("")
    return "\n".join(lines)


def write_markdown(results: List[dict], path: str) -> str:
    body = ["# Results", "",
            "Generated by `python cli.py compare` from the JSON files in this folder. "
            "Rel. L2 vs FP32 = ||a - a_fp32|| / ||a_fp32|| over the action chunk, same frames and noise. "
            "MSE vs GT is in the dataset's (unnormalized) action units.", ""]
    body += [markdown_for(r) for r in results]
    text = "\n".join(body)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return text


def plot_result(result: dict, path: str) -> Optional[str]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = [v for v in result["variants"] if "skipped" not in v]
    if not rows:
        return None
    names = [v["variant"] for v in rows]
    p50 = [v["latency"]["inference"]["p50_ms"] for v in rows]
    lo = [p - v["latency"]["inference"]["p50_ci95_ms"][0] for p, v in zip(p50, rows)]
    hi = [v["latency"]["inference"]["p50_ci95_ms"][1] - p for p, v in zip(p50, rows)]
    rel = [v["agreement_with_fp32"]["rel_l2_mean"] for v in rows]
    floor = next((v["noise_floor"]["rel_l2_mean"] for v in rows if "noise_floor" in v), None)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))
    env = result["environment"]
    fig.suptitle(f"{result['model']['model_key']} - {env['device']} ({env.get('gpu') or env.get('cpu')})", fontsize=11)
    x = range(len(names))
    ax1.bar(x, p50, yerr=[lo, hi], capsize=4, color="#4C72B0")
    ax1.set_xticks(list(x))
    ax1.set_xticklabels(names, rotation=25, ha="right")
    ax1.set_ylabel("p50 latency (ms), 95% CI")
    ax1.set_title(f"Inference latency (n={rows[0]['latency']['inference']['n']} per variant)")
    ax2.bar(x, rel, color="#DD8452")
    if floor is not None:
        ax2.axhline(floor, ls="--", color="gray", label="FP32 noise floor")
        ax2.legend()
    ax2.set_xticks(list(x))
    ax2.set_xticklabels(names, rotation=25, ha="right")
    ax2.set_ylabel("relative L2 error vs FP32 actions")
    ax2.set_title("Output change vs FP32 (same frames, same noise)")
    fig.tight_layout()
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return path
